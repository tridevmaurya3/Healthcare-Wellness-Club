  supplier_id BIGINT UNSIGNED NOT NULL,
  purchase_bill_id BIGINT UNSIGNED NOT NULL,
  return_number VARCHAR(90) NOT NULL,
  return_date DATE NOT NULL,
  reason TEXT NOT NULL,
  total_credit DECIMAL(16,2) NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'posted',
  raw_source_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_purchase_return_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_purchase_return_supplier FOREIGN KEY (supplier_id) REFERENCES purchase_suppliers(id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_return_bill FOREIGN KEY (purchase_bill_id) REFERENCES purchase_bills(id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_return_raw FOREIGN KEY (raw_source_id) REFERENCES raw_source_records(id) ON DELETE SET NULL,
  UNIQUE KEY uq_purchase_return_number (organization_id, return_number),
  KEY idx_purchase_return_bill (organization_id, purchase_bill_id, return_date)
