CREATE TABLE IF NOT EXISTS purchase_payments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  organization_id BIGINT UNSIGNED NOT NULL,
  supplier_id BIGINT UNSIGNED NOT NULL,
  purchase_bill_id BIGINT UNSIGNED NOT NULL,
  payment_date DATE NOT NULL,
  amount DECIMAL(16,2) NOT NULL,
  payment_method VARCHAR(50) NOT NULL DEFAULT 'other',
  reference_no VARCHAR(150) NULL,
  notes TEXT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'active',
  raw_source_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_purchase_payment_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_purchase_payment_supplier FOREIGN KEY (supplier_id) REFERENCES purchase_suppliers(id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_payment_bill FOREIGN KEY (purchase_bill_id) REFERENCES purchase_bills(id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_payment_raw FOREIGN KEY (raw_source_id) REFERENCES raw_source_records(id) ON DELETE SET NULL,
  KEY idx_purchase_payment_bill (organization_id, purchase_bill_id, status, payment_date),
  KEY idx_purchase_payment_supplier (organization_id, supplier_id, status, payment_date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS purchase_returns (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
