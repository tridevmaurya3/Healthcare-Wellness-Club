  purchase_receipt_id BIGINT UNSIGNED NOT NULL,
  purchase_bill_item_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  listing_id BIGINT UNSIGNED NOT NULL,
  quantity_received DECIMAL(16,3) NOT NULL,
  unit_cost DECIMAL(16,2) NOT NULL,
  batch_code VARCHAR(120) NOT NULL,
  manufacture_date DATE NULL,
  expiry_date DATE NULL,
  inventory_transaction_id BIGINT UNSIGNED NOT NULL,
  inventory_batch_id BIGINT UNSIGNED NOT NULL,
  returned_quantity DECIMAL(16,3) NOT NULL DEFAULT 0,
  use_as_profit_cost TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_purchase_receipt_item_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_purchase_receipt_item_receipt FOREIGN KEY (purchase_receipt_id) REFERENCES purchase_receipts(id) ON DELETE CASCADE,
